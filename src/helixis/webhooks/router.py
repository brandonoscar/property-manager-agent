"""POST /webhooks/buildium — inbound webhook receiver.

Responsibilities:
1. Capture the raw request body BEFORE JSON parsing (signature is over bytes).
2. Parse just the envelope to extract ``AccountId``.
3. Resolve the company for that AccountId and load its webhook secret.
4. HMAC-verify the request against that company-specific secret.
5. Persist into the ``buildium_events`` queue (durable audit + work item).
6. Return 200 within Buildium's 10-second deadline.

Auth: signature IS the auth. Do NOT mount any auth middleware on this route.

Per Buildium's spec
(https://developer.buildium.com — Verifying webhook events):
the secret is generated by Buildium when the user creates the webhook
subscription and pasted into Helixis by the user. We do not generate it.

Headers:
  - buildium-webhook-timestamp: UNIX seconds (string).
  - buildium-webhook-signature: base64(HMACSHA256(timestamp + "." + body)).

We read both off ``request.headers`` directly to avoid FastAPI's
underscore-to-hyphen header magic — some ingress proxies (Render,
Vercel) normalise header casing in ways that confuse it.
"""

