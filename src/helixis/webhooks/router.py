# ── The receiver's own clock ──────────────────────────────────────────
#
# ⚠ **Nothing bounded the synchronous work, and the consequence of exceeding
# it is silent and total.** Buildium gives a webhook receiver ten seconds and
# suspends the subscription after 20 consecutive failures — at which point ALL
# webhook ingestion stops until someone re-enables it in the Buildium console.
# There is no alarm for that; the Inbox simply goes quiet.
#
# The module comment estimated the budget as "enrichment (~800ms) + routing
# (~50ms) + floor builder (~5ms) + legacy dispatch (already in path) —
# comfortably under 10s". Every term but the last two is an ESTIMATE of work
# that makes live Buildium calls: the enricher fetches the task, its unit, its
# property and its requester, and `dispatch_event`'s handlers each re-fetch
# their own entity (queue.py's own comment: "mirror handlers hold the window
# open for seconds because they fetch from Buildium"). Add the client's
# account-wide 10 req/s token bucket and a slow upstream, and the estimate is
# not a bound.
#
# So the two slow phases share an explicit deadline. On expiry they degrade
# down the path they ALREADY have for a crash — the row is durably enqueued
# before any of this runs, the claim is released, and the worker redoes it
# with no per-call time pressure. Late is fine; a suspended subscription is
# not.
BUILDIUM_ACK_SLA_SECONDS = 10.0
"""Buildium's deadline for a 2XX. Their number, not ours."""

RECEIVER_WORK_BUDGET_SECONDS = BUILDIUM_ACK_SLA_SECONDS * 0.6
"""How long the receiver may spend on enrichment + legacy dispatch COMBINED.

A fraction of the SLA rather than a round number, so it moves if Buildium's
deadline ever does. The remaining 40% covers signature verification, the
enqueue, routing, the floor build, the claim resolution and the response
itself — all of which happen outside this budget and none of which are free.
"""


class _ReceiverDeadline:
    """A single budget shared by both slow phases, so whatever enrichment does
    not spend is still available to dispatch.

    Two separate timeouts would let the worst case be the SUM of them, which
    is the number that has to stay under the SLA — the same reasoning as the
    agent's ``CallLedger`` (gotcha 32), one layer down.
    """

    def __init__(self, budget: float = RECEIVER_WORK_BUDGET_SECONDS) -> None:
        self._deadline = time.monotonic() + budget

    def remaining(self) -> float:
        return max(0.0, self._deadline - time.monotonic())


async def _within_deadline(coro: Any, deadline: _ReceiverDeadline) -> None:
    """Await ``coro`` inside what is left of the receiver's budget.

    ⚠ ``SystemExit`` is converted INSIDE the wrapper, before it crosses the
    Task boundary ``wait_for`` creates. Catching it outside does not contain
    it: asyncio re-raises ``SystemExit`` into the running loop as well as to
    the awaiter, so the handler returns its degraded value exactly as designed
    and the process dies a moment later (gotcha 36). An optional ML dep can
    still ``sys.exit(1)`` at runtime (gotcha 7), and this is a request path.
    """

    async def _guarded() -> None:
        try:
            await coro
        except SystemExit as exc:  # noqa: TRY302 — must not cross the Task boundary
            raise RuntimeError(f"SystemExit inside receiver work: {exc}") from exc

    await asyncio.wait_for(_guarded(), timeout=deadline.remaining())


async def _await_enrichment(
    handler: Any, envelope_dict: dict[str, Any], company_id: str, deadline: _ReceiverDeadline
) -> Any:
    """Run one enricher inside the receiver's budget and return its result.

    Separate from :func:`_within_deadline` because this one has a RETURN
    VALUE — the enriched event — and a shared helper that discarded it would
    be the same bug as gotcha 42's ``.as_tool(max_turns=)``, which threw away
    a sub-run that had already found what it needed.
    """
    result: list[Any] = []

    async def _run() -> None:
        result.append(await handler.enricher.enrich(envelope_dict, company_id))

    await _within_deadline(_run(), deadline)
    return result[0]


router = APIRouter(tags=["webhooks"])


@router.post("/webhooks/buildium", status_code=status.HTTP_200_OK)
async def buildium_webhook(request: Request) -> dict[str, Any]:
    # Rate limit FIRST — cheaper than HMAC verification, so a misbehaving
    # sender can't burn CPU by flooding bogus signatures.
    #
    # ⚠ This bounds FORGED traffic, not customers. The key is the SENDER'S ip
    # and every company's events arrive from Buildium's egress, so it is one
    # shared bucket for the whole deployment — at ~600/min per busy account
    # (config/default.yaml) a third customer syncing at the same time crosses
    # it. `refund_by_ip` below is what stops that costing a real event: a
    # request that verifies stops consuming the budget, so only unverifiable
    # traffic can exhaust it.
    #
    # ⚠ The comment this replaces claimed "Buildium itself is capped at
    # ~10 RPS, so 120/min gives 2x headroom" while the limiter read 1200 and
    # the YAML said 600 — three numbers in three places, none of them checked
    # against the others (gotcha 48). The ONE number lives in
    # `config/default.yaml` and nothing here restates it.
    await webhook_limiter.check_by_ip(request)

    timestamp = request.headers.get("buildium-webhook-timestamp")
    signature = request.headers.get("buildium-webhook-signature")

    # PR #79 — Buildium probes the destination URL with an UNSIGNED
    # request before saving a webhook subscription, because the secret
    # hasn't been written on their side yet (there's nothing to sign
    # with). Pre-PR-#79 we 401'd the probe → Buildium concluded the
    # URL was unreachable and aborted the save with a generic red
    # "Something went wrong" banner.
    #
    # Fix: if BOTH signature headers are absent AND the body doesn't
    # look like a real event envelope, treat it as a validation probe
    # and return 200 OK so the subscription saves. Real Buildium
    # webhook traffic ALWAYS carries both headers — an unsigned
    # request with a real-looking envelope is either an attacker
    # forging events or a Buildium bug, and still 401's below.
    raw_body = await request.body()
    if not timestamp and not signature:
        if _looks_like_validation_probe(raw_body):
            logger.info(
                "Buildium webhook validation probe from %s — returning 200 OK"
                " so the subscription can save.",
                request.client.host if request.client else "unknown",
            )
            capture(
                distinct_id="system",
                event="webhook_validation_probe_accepted",
                properties={"source": "buildium_webhook"},
            )
            return {"status": "ok", "message": "webhook endpoint live"}
        # An unsigned request with a real-looking envelope falls
        # through to the 401 below — that's hostile traffic, not a
        # probe.

    if not timestamp or not signature:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Missing signature headers",
        )

    # Parse just enough of the envelope to extract AccountId. We can't
    # verify the signature until we know which company's secret to use,
    # and AccountId in the envelope is how Buildium tells us.
    try:
        envelope_dict = json.loads(raw_body.decode("utf-8"))
        account_id = int(envelope_dict["AccountId"])
    except (KeyError, TypeError, ValueError, json.JSONDecodeError) as exc:
        logger.warning("Buildium webhook envelope malformed: %s", exc)
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Invalid envelope",
        ) from None

    # Resolve company by AccountId. If we don't recognise the account,
    # acknowledge with 200 + a warning log (NOT 401) — a 401 would burn
    # Buildium's retry budget for an event we'll never want anyway.
    resolved = await load_webhook_secret_by_account_id(account_id)
    if resolved is None:
        logger.warning(
            "Buildium webhook for unknown or unconfigured AccountId %s "
            "(event=%s) — returning 200 to avoid retry storm.",
            account_id,
            envelope_dict.get("EventName"),
        )
        capture(
            distinct_id="system",
            event="webhook_dropped_unknown_account",
            properties={
                "account_id": account_id,
                "event_name": envelope_dict.get("EventName"),
                "source": "buildium_webhook",
            },
        )
        return {"status": "unknown_account"}

    company_id, secret = resolved

    settings = get_settings().buildium
    try:
        verify_signature(
            secret=secret,
            timestamp=timestamp,
            signature=signature,
            raw_body=raw_body,
            freshness_seconds=settings.signature_freshness_seconds,
        )
    except SignatureVerificationError as exc:
        logger.warning(
            "Buildium webhook signature rejected for company=%s account=%s: %s",
            company_id,
            account_id,
            exc,
        )
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Invalid signature",
        ) from None

    # AUTHENTIC — this request carries a signature made with this company's own
    # webhook secret, so give the abuse budget its slot back. Placed exactly
    # here and nowhere earlier: the validation-probe branch above is unsigned
    # by definition and the unknown-account branch has not verified anything,
    # so refunding at either would hand the budget to traffic we cannot vouch
    # for. From here on the only thing the ceiling can shed is a forgery.
    webhook_limiter.refund_by_ip(request)

    # Validate envelope shape now that we trust the bytes. Unknown
    # event names are still accepted — the dispatcher decides whether
    # to handle, ignore, or log them.
    try:
        envelope = BuildiumEventEnvelope.model_validate(envelope_dict)
    except Exception as exc:
        logger.warning("Buildium webhook envelope invalid: %s", exc)
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Invalid event envelope",
        ) from None

    # Display gate (allowlist). The Inbox surfaces only genuinely
    # actionable events — tasks, work orders, resident requests, and
    # leasing-pipeline milestones (see ``inbox_filter``). Everything
    # else Buildium sends (rent payments/charges, lease transactions,
    # tenant-identity edits, bills, owner-ledger bookkeeping, GL setup)
    # is accepted and audited but never shown. The PR #82/#83
    # routing+surface pipeline below predated this gate, so a Buildium
    # owner-charge billing run (e.g. 20 ``OwnershipAccountTransaction``
    # in one morning) fanned out 20 bare "assigned to the admin" cards
    # into the General lane.
    #
    # For non-surfaced events we still enqueue (durable audit) and still
    # run legacy dispatch, but we skip enrichment + routing +
    # surface-building so no misleading admin-assignment decision is
    # written and no Buildium API calls fire for an event we won't
    # display. The Inbox feed applies the same allowlist (see
    # ``recent_events``), which also hides rows already on disk.
    surface_in_inbox = surfaces_in_inbox(envelope.event_name)

    # Persist + enqueue. Duplicates are safe — we return 200 either way
    # so Buildium does not retry indefinitely on a redelivery.
    #
    # claim_by: the receiver processes the event INLINE below (enrichment +
    # legacy dispatch), so the fresh row is inserted already claimed —
    # otherwise the worker's poll picks up the still-pending row mid-flight
    # and runs the same handler a second time in parallel (live-observed on
    # applicant 5045, 2026-07-05: mirror handlers hold the window open for
    # seconds because they fetch from Buildium). On failure we release the
    # claim so the worker retries; if this process dies mid-flight, the
    # worker's stale-running janitor requeues the row.
    pool = get_pool()
    result = await enqueue(
        pool,
        event_name=envelope.event_name,
        event_time=envelope.event_date_time,
        account_id=envelope.account_id,
        company_id=company_id,
        entity_ids=envelope.entity_ids(envelope_dict),
        payload=envelope_dict,
        claim_by="receiver",
    )

    # The receiver's synchronous budget starts HERE — after the row is durably
    # enqueued, so an expiry can never lose an event, only defer it.
    deadline = _ReceiverDeadline()

    # Phase A.0 — enrichment first (PR #83). The PR #82 deterministic
    # surface used to be built from the bare envelope, but real
    # Buildium ``Task.Created`` payloads only carry TaskId + EventName
    # — no title, no property, no assignee — so the floor rendered
    # bare strings like "Task.Created — assigned to Vinny Dan". PR
    # #83 fans out via the registered EventEnricher first so the
    # floor can use task title + unit address + requester name.
    #
    # We DECOUPLE enricher from planner here (vs. the legacy
    # ``handler.run()`` which runs both together) so a planner
    # failure (PR #84 territory — Gemini silently 0/2 since May 16)
    # doesn't dark-hole the enrichment.
    enrichment_handler = get_enrichment_handler(envelope.event_name)
    enriched_event: Any = None  # EnrichedEvent | None — typed-Any to avoid import noise
    enrichment_dict: dict[str, Any] | None = None
    enrichment_ok = True
    if enrichment_handler is not None and not result.duplicate and surface_in_inbox:
        try:
            enriched_event = await _await_enrichment(
                enrichment_handler, envelope_dict, company_id, deadline
            )
            enrichment_dict = enriched_event.model_dump(mode="json")
        except TimeoutError:
            enrichment_ok = False
            logger.warning(
                "enrichment exceeded the receiver's budget for event %s (id=%s) — "
                "releasing to the worker, which has no ack deadline",
                envelope.event_name,
                result.id,
            )
        except Exception as exc:  # noqa: BLE001 — enrichment is best-effort
            enrichment_ok = False
            logger.exception(
                "PR #83 enrichment failed for event %s (id=%s); deterministic "
                "floor will render from the bare envelope",
                envelope.event_name,
                result.id,
            )
            # Capture so the audit can see which rows fell through.
            try:
                await mark_enrichment_failed(pool, result.id, error=repr(exc))
            except Exception:  # noqa: BLE001
                logger.exception(
                    "Could not persist enrichment failure to row %s",
                    result.id,
                )

    # Phase A.1 — deterministic routing (PR #82, extended by PR #83
    # to consume the enrichment we just loaded). ALWAYS runs.
    # Produces an ``action_surface`` rich when enrichment landed,
    # bare-envelope when it didn't — either way the Inbox lights up.
    #
    # Wrapped in a single ``except Exception`` because routing must
    # NEVER 500 the receiver: Buildium suspends subscriptions after
    # 20 consecutive non-2xx.
    deterministic_surface: dict[str, Any] | None = None
    if not result.duplicate and surface_in_inbox:
        try:
            routing_decision = await route_event(
                pool,
                event_name=envelope.event_name,
                envelope=envelope_dict,
                company_id=company_id,
            )
            staff_cache = await load_staff_cache(pool, company_id)
            deterministic_surface = build_action_surface_from_routing(
                envelope=envelope_dict,
                event_name=envelope.event_name,
                decision=routing_decision,
                staff_cache=staff_cache,
                enriched=enriched_event,
            )
            await store_routing_decision(
                pool,
                result.id,
                decision={
                    "action_type": routing_decision.action_type,
                    "assigned_buildium_user_id": routing_decision.assigned_buildium_user_id,
                    "assigned_helixis_user_id": routing_decision.assigned_helixis_user_id,
                    "surface": routing_decision.surface,
                    "reason": routing_decision.reason,
                },
                deterministic_surface=deterministic_surface,
                enrichment=enrichment_dict,
            )
        except Exception:  # noqa: BLE001 — receiver must return 200
            logger.exception(
                "PR #82 routing failed for event %s (id=%s); falling through to legacy path",
                envelope.event_name,
                result.id,
            )

    # Phase A.2 — planner step. The LLM call USED to run synchronously
    # here, but at ``_LLM_TIMEOUT_SECONDS = 8s`` (chosen to stay inside
    # Buildium's 10s SLA) it consistently timed out for Gemini 2.5
    # Flash on structured-JSON output (~5-12s typical, up to ~20s on
    # cold connections). Production rows 0fd4e984 / fcb56b89 silently
    # fell back to the deterministic floor for weeks.
    #
    # PR #89 moves the planner into the worker
    # (``webhooks/worker.py:_process_planner_batch``). The receiver
    # leaves ``planner_status='pending'`` on the freshly-enqueued row
    # (DB default from migration 0017) and the worker claims it on
    # its next poll. The deterministic floor above still writes
    # ``action_surface`` inline, so the inbox has something to render
    # between receiver-ack and worker-completion. The frontend reads
    # ``planner_status`` to decide whether to shimmer ("thinking…"),
    # show the surface, or offer a Replan affordance.
    #
    # Receiver SLA budget after this change: enrichment (~800ms)
    # + routing (~50ms) + floor builder (~5ms) + legacy dispatch
    # (already in path) — comfortably under 10s.

    # Legacy synchronous dispatch: the per-category handlers under
    # ``helixis.webhooks.handlers`` continue to run for backwards
    # compat. For events the enrichment registry covers, their work
    # is redundant with the new path but cheap (a single activity-log
    # write) — keeping it in place means no behaviour regression for
    # downstream consumers that already watch activity rows.
    #
    # Per Buildium spec we MUST return 2XX on success or risk
    # subscription suspension after 20 consecutive failures. If a
    # handler crashes we log loudly and return 200 — we release the
    # receiver's claim below so the worker retries.
    #
    # Skipped for redeliveries: the original delivery either finished
    # (row done) or is with the worker (row pending) — re-running the
    # handler inline would just duplicate its writes.
    dispatch_ok = True
    if not result.duplicate:
        try:
            await _within_deadline(
                dispatch_event(company_id, envelope.event_name, envelope_dict), deadline
            )
        except TimeoutError:
            dispatch_ok = False
            logger.warning(
                "legacy dispatch exceeded the receiver's budget for event %s (id=%s) — "
                "releasing to the worker, which has no ack deadline",
                envelope.event_name,
                result.id,
            )
        except Exception:  # noqa: BLE001
            dispatch_ok = False
            logger.exception(
                "Handler crashed for event %s (id=%s); releasing to the worker to retry",
                envelope.event_name,
                result.id,
            )

    # The receiver inserted the fresh row CLAIMED (claim_by above), so it
    # must resolve the claim: mark done when BOTH enrichment (when
    # applicable) AND legacy dispatch succeeded, else release the row back
    # to pending so the worker retries the failed half.
    #
    # Guarded: at this point the event is durably enqueued — a transient DB
    # failure on this one UPDATE must not 500 the receiver (each non-2xx
    # burns Buildium retry budget; 20 consecutive suspend the
    # subscription). Worst case the row stays ``running`` until the
    # worker's stale-running janitor requeues it — delayed, never lost.
    if not result.duplicate:
        try:
            if enrichment_ok and dispatch_ok:
                await mark_done(pool, result.id)
            else:
                await release_claim(pool, result.id)
        except Exception:  # noqa: BLE001 — receiver must return 200
            logger.exception(
                "claim resolution failed for event %s (id=%s); stale-running janitor will requeue",
                envelope.event_name,
                result.id,
            )

    logger.info(
        "Buildium webhook accepted id=%s event=%s duplicate=%s company=%s",
        result.id,
        envelope.event_name,
        result.duplicate,
        company_id,
    )

    return {
        "id": str(result.id),
        "event_name": envelope.event_name,
        "duplicate": result.duplicate,
    }


def _looks_like_validation_probe(body: bytes) -> bool:
    """True if ``body`` does NOT look like a real Buildium webhook envelope.

    PR #79 — Buildium's pre-save validation ping is unsigned (the
    secret isn't on their side yet), so we can't fall back on
    signature verification to tell probe from real traffic. We use
    the body shape instead: a real envelope is JSON carrying at
    minimum ``AccountId`` AND ``EventName`` (Buildium's spec
    guarantees both on every event). Anything else — empty body,
    plain text, JSON missing those fields — is treated as a probe.

    Oversized bodies are NOT treated as probes: a 4KB+ unsigned
    payload is suspicious and falls through to the 401 path so we
    don't silently swallow large hostile requests.
    """
    if not body:
        return True
    if len(body) > 4096:
        return False
    try:
        parsed = json.loads(body.decode("utf-8"))
    except (json.JSONDecodeError, UnicodeDecodeError):
        return True
    if not isinstance(parsed, dict):
        return True
    has_account = "AccountId" in parsed
    has_event = "EventName" in parsed or "Event" in parsed
    return not (has_account and has_event)
